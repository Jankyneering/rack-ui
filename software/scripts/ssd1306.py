"""Minimal SSD1306 128x64 OLED driver for the host-side test scripts.

Drives the display directly through an i2cdriver.I2CDriver instance on the
same bus as the rack-ui MCU, so no firmware changes are needed. No external
dependencies: a classic 5x7 bitmap font is embedded.

Coordinate system: (0,0) is the top-left corner, x grows to the right, y grows
down. The framebuffer is page-major: one byte per column covers 8 vertical
pixels, LSB = topmost row of the page. On the common two-color modules the
top 16 rows (y 0-15) are yellow and the rest is blue, which makes rows 0-15 a
natural title band.
"""

