FONT_WIDTH = 5
FONT_HEIGHT = 7
FONT_ADVANCE = FONT_WIDTH + 1  # one blank column between characters


class SSD1306:
    def __init__(self, i2c, address=0x3C, width=WIDTH, height=HEIGHT):
        self.i2c = i2c
        self.address = address
        self.width = width
        self.height = height
        self.pages = height // 8
        self.buffer = bytearray(width * self.pages)
        self.shadow = bytearray(width * self.pages)
        self.init()

    def init(self):
        mux = self.height - 1
        com_pins = 0x12 if self.pages > 4 else 0x02
        self.command(
            0xAE,  # display off
            0xD5, 0x80,  # clock divide / oscillator
            0xA8, mux,  # multiplex ratio
            0xD3, 0x00,  # display offset
            0x40,  # display start line 0
            0x8D, 0x14,  # charge pump enable
            0x20, 0x00,  # horizontal addressing mode
            0xA1,  # segment remap: column 127 = SEG0
            0xC8,  # COM scan direction: remapped
            0xDA, com_pins,  # COM pins configuration
            0x81, 0x8F,  # contrast
            0xD9, 0x22,  # pre-charge period
            0xDB, 0x40,  # VCOMH deselect level
            0xA4,  # display follows RAM
            0xA6,  # normal (non-inverted) display
        )
        self.command(0xAF)  # display on

    def command(self, *cmds):
        self.i2c.start(self.address, 0)
        self.i2c.write(bytes([CMD]) + bytes(cmds))
        self.i2c.stop()

    def power(self, on):
        self.command(0xAF if on else 0xAE)

    def invert(self, on):
        self.command(0xA7 if on else 0xA6)

    # --- framebuffer ---

    def clear(self):
        self.buffer = bytearray(len(self.buffer))

    def pixel(self, x, y, on=True):
        if not (0 <= x < self.width and 0 <= y < self.height):
            return
        page, bit = y >> 3, y & 7
        index = page * self.width + x
        if on:
            self.buffer[index] |= 1 << bit
        else:
            self.buffer[index] &= ~(1 << bit) & 0xFF

    def fill_rect(self, x, y, w, h, on=True):
        for dy in range(h):
            for dx in range(w):
                self.pixel(x + dx, y + dy, on)

    def rect(self, x, y, w, h, on=True):
        self.hline(x, y, w, on)
        self.hline(x, y + h - 1, w, on)
        self.vline(x, y, h, on)
        self.vline(x + w - 1, y, h, on)

    def hline(self, x, y, w, on=True):
        for dx in range(w):
            self.pixel(x + dx, y, on)

    def vline(self, x, y, h, on=True):
        for dy in range(h):
            self.pixel(x, y + dy, on)

    # --- text ---

    def text(self, x, y, s, on=True):
        """Draw a string with the 5x7 font; returns the x after the last glyph."""
        for ch in s:
            code = ord(ch)
            if not (0x20 <= code <= 0x7E):
                code = 0x20
            glyph = FONT5X7[(code - 0x20) * FONT_WIDTH : (code - 0x20 + 1) * FONT_WIDTH]
            for col, bits in enumerate(glyph):
                for row in range(FONT_HEIGHT):
                    if bits & (1 << row):
                        self.pixel(x + col, y + row, on)
            x += FONT_ADVANCE
        return x

    def text_width(self, s):
        return len(s) * FONT_ADVANCE - 1 if s else 0

    def text_centered(self, y, s, on=True):
        self.text(max(0, (self.width - self.text_width(s)) // 2), y, s, on)

    # --- transfer ---

    def _set_window(self, page):
        self.command(0x21, 0, self.width - 1, 0x22, page, page)

    def flush(self):
        """Send only the pages whose contents changed since the last flush."""
        for page in range(self.pages):
            start = page * self.width
            seg = self.buffer[start : start + self.width]
            if seg == self.shadow[start : start + self.width]:
                continue
            self._set_window(page)
            self.i2c.start(self.address, 0)
            self.i2c.write(bytes([DATA]) + bytes(seg))
            self.i2c.stop()
            self.shadow[start : start + self.width] = seg


def probe(i2c):
    """Return an initialized SSD1306 for the first display found on the bus,
    or None when no display answers (it is an optional board component)."""
    scan = getattr(i2c, "scan", None)
    if scan is not None:
        try:
            found = scan(silent=True)
        except TypeError:
            found = scan()
        for address in I2C_ADDRESSES:
            if address in found:
                return SSD1306(i2c, address)
        return None
    for address in I2C_ADDRESSES:
        try:
            return SSD1306(i2c, address)
        except Exception:
            continue
    return None
